// Current year
document.getElementById("year").textContent = new Date().getFullYear();

// Mobile navigation
const menuToggle = document.getElementById("menuToggle");
const navLinks = document.getElementById("navLinks");

menuToggle.addEventListener("click", () => {
    const isOpen = navLinks.classList.toggle("open");
    menuToggle.setAttribute("aria-expanded", String(isOpen));
});

document.querySelectorAll("#navLinks a").forEach(link => {
    link.addEventListener("click", () => {
        navLinks.classList.remove("open");
        menuToggle.setAttribute("aria-expanded", "false");
    });
});

// Publication filters
const filterButtons = document.querySelectorAll(".filter-btn");
const publications = document.querySelectorAll(".publication-item");

filterButtons.forEach(button => {
    button.addEventListener("click", () => {
        filterButtons.forEach(btn => btn.classList.remove("active"));
        button.classList.add("active");

        const filter = button.dataset.filter;

        publications.forEach(item => {
            item.style.display =
                filter === "all" || item.dataset.type === filter
                    ? "grid"
                    : "none";
        });
    });
});

// Active navigation state
const sections = document.querySelectorAll("main section[id]");
const navItems = document.querySelectorAll(".nav-links a");

const observer = new IntersectionObserver(
    entries => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                navItems.forEach(item => item.classList.remove("active"));

                const active = document.querySelector(
                    `.nav-links a[href="#${entry.target.id}"]`
                );

                if (active) active.classList.add("active");
            }
        });
    },
    {
        rootMargin: "-25% 0px -65% 0px",
        threshold: 0
    }
);

sections.forEach(section => observer.observe(section));

// Google Scholar citation dashboard. The JSON file is generated by GitHub Actions.
async function loadScholarDashboard() {
    const profileLink = document.getElementById("scholar-profile-link");
    const updatedLabel = document.getElementById("scholar-updated");

    try {
        const response = await fetch("./data/scholar.json", { cache: "no-store" });
        if (!response.ok) throw new Error("Scholar data unavailable");

        const data = await response.json();
        const profile = data.profile || {};

        document.getElementById("scholar-total-citations").textContent =
            Number.isFinite(Number(profile.total_citations)) ? profile.total_citations : "—";
        document.getElementById("scholar-h-index").textContent =
            Number.isFinite(Number(profile.h_index)) ? profile.h_index : "—";
        document.getElementById("scholar-i10-index").textContent =
            Number.isFinite(Number(profile.i10_index)) ? profile.i10_index : "—";

        if (profile.url) profileLink.href = profile.url;
        updatedLabel.textContent = data.last_updated
            ? "Data last refreshed: " + new Date(data.last_updated).toLocaleString()
            : "Citation data has not been refreshed yet.";

        // Match citation counts to the publication titles already listed on this homepage.
        const normalize = value => (value || "").toLowerCase()
            .replace(/[^a-z0-9]+/g, " ").trim();
        const citationByTitle = new Map();
        (data.publications || []).forEach(paper => {
            const key = normalize(paper.title);
            if (key) citationByTitle.set(key, paper.citations ?? 0);
        });

        document.querySelectorAll(".publication-item").forEach(item => {
            const titleElement = item.querySelector(".pub-title");
            if (!titleElement) return;
            const key = normalize(titleElement.textContent);
            let citations = citationByTitle.get(key);

            // A partial title match helps when Scholar includes subtitle punctuation differences.
            if (citations === undefined) {
                for (const [knownTitle, count] of citationByTitle.entries()) {
                    if (knownTitle && (knownTitle.includes(key) || key.includes(knownTitle))
                        && Math.min(knownTitle.length, key.length) > 24) {
                        citations = count;
                        break;
                    }
                }
            }

            const existing = item.querySelector(".pub-citation-count");
            if (existing) existing.remove();
            if (citations !== undefined) {
                const badge = document.createElement("span");
                badge.className = "pub-citation-count";
                badge.textContent = "Google Scholar citations: " + citations;
                titleElement.insertAdjacentElement("afterend", badge);
            }
        });
    } catch (error) {
        updatedLabel.textContent = "Citation data is temporarily unavailable; see Google Scholar for current metrics.";
        // Keep the rest of the academic homepage usable if retrieval fails.
    }
}

loadScholarDashboard();

